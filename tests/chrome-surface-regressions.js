"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const css = fs.readFileSync(path.join(root,'src/styles/chrome-surface.css'),'utf8').replace(/\/\*[\s\S]*?\*\//g,'');
const manifest = JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const files = manifest.content_scripts[0].css;
assert.ok(files.indexOf('src/styles/chrome-surface.css') > files.indexOf('src/styles/interface-refinement.css'));
assert.equal(files.filter(x=>x==='src/styles/chrome-surface.css').length,1);
assert.match(css, /#frosted-glass\s*\{[^}]*z-index:\s*1999\s*!important/);
assert.match(css, /#frosted-glass::before\s*\{[^}]*inset:\s*0\s*;/);
assert.match(css, /ytd-browse #primary\s*\{[^}]*z-index:\s*auto\s*!important/);
assert.match(css, /ytSearchboxComponentInputBox[^}]*backdrop-filter:\s*none\s*!important/);
assert.match(css,/data-ylg-chrome-lens="1"[^}]*#frosted-glass::before\s*\{[^}]*url\(#ylg-lens-chrome\)/);
assert.match(css, /data-ylg-fill="none"[^}]*content:\s*none/);
assert.match(css, /#frosted-glass\s*\{[^}]*height:\s*var\(--ytd-masthead-height, 56px\)\s*!important/);
assert.match(css, /#frosted-glass\s*\{[^}]*overflow:\s*hidden\s*!important/);
assert.match(css, /#frosted-glass\s*\{[^}]*clip-path:\s*none\s*!important/);
assert.match(css, /#frosted-glass::before\s*\{[^}]*clip-path:\s*inset\(0 round 0 0 10px 10px\)/);
assert.doesNotMatch(css, /#frosted-glass\s*\{[^}]*clip-path:\s*inset/);
assert.match(css, /ytd-app\[is-watch-page\]:not\(\[fullscreen\]\) #frosted-glass\s*\{[^}]*display:\s*block\s*!important/);
assert.match(css, /inset 0 0 0 1px color-mix\(in srgb, var\(--ylg-rim-light\)/);
assert.match(css, /InputBox[^}]*background-color:\s*var\(--yt-sys-color-baseline--tonal-background/);
assert.match(css, /backdrop-filter:\s*blur\(var\(--ylg-blur, 0px\)\) url\(#ylg-lens-chrome\)/);
assert.doesNotMatch(css, /ytd-app:has\(\s*>\s*#frosted-glass\s*\)/, "#frosted-glass lives inside ytd-app > #content, not as a direct child of ytd-app");
assert.match(css, /html\[data-ylg-enabled="true"\]:has\(#frosted-glass\)\s+#masthead-container#masthead-container\s+ytd-masthead\.ylg-glass/);
const ceilingCss = fs.readFileSync(path.join(root,'src/styles/opacity-ceiling.css'),'utf8').replace(/\/\*[\s\S]*?\*\//g,'');
assert.match(ceilingCss, /@layer ylg-ceiling\s*\{[\s\S]*:has\(#frosted-glass\)\s+#masthead-container\s+:is\(ytd-masthead,\s*#masthead,\s*ytd-searchbox\)\.ylg-glass\s*\{[^}]*background-color:\s*transparent\s*!important/);
console.log('Chrome surface regressions: 20/20 passed (source contracts only; browser rendering requires separate verification).');
